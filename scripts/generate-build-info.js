const fs = require('fs');
const path = require('path');

const packageJsonPath = path.resolve(__dirname, '../package.json');
const outputPath = path.resolve(__dirname, '../addon/lib/buildInfo.js');
const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));

// A second, independent version tracker for this fork, separate from the
// upstream aiometadata version above. Bump this by hand when you want to
// mark a new personal build (e.g. "AER 1.1").
const AER_VERSION = 'AER 1.0';

const output = `// Generated by scripts/generate-build-info.js. Do not edit manually.
module.exports = {
  name: ${JSON.stringify(packageJson.name)},
  version: ${JSON.stringify(packageJson.version)},
  aerVersion: ${JSON.stringify(AER_VERSION)}
};
`;

fs.writeFileSync(outputPath, output);
